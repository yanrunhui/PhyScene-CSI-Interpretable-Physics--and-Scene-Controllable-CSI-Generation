#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Mapping

import torch

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from physics_csi.evaluation.aod_support import enforce_final_strongest_anchor
from physics_csi.models.scene_delay_power_residual import (
    SceneConditionedDelayPowerResidual,
)
from physics_csi.physics.synthesizer import MIMOOFDMSynthesizer, SystemConfig
from physics_csi.training.trainer import resolve_device


def _sample_count(payload: Mapping[str, Any]) -> int:
    return int(payload["path_mask"].shape[0])


def _subset(
    payload: Mapping[str, Any], start: int, stop: int, device: torch.device
) -> dict[str, torch.Tensor]:
    samples = _sample_count(payload)
    return {
        key: value[start:stop].to(device)
        for key, value in payload.items()
        if isinstance(value, torch.Tensor) and value.shape[:1] == (samples,)
    }


def _append(
    chunks: dict[str, list[torch.Tensor]], payload: Mapping[str, torch.Tensor]
) -> None:
    for key, value in payload.items():
        if isinstance(value, torch.Tensor):
            chunks.setdefault(key, []).append(value.detach().cpu())


def _finish(chunks: Mapping[str, list[torch.Tensor]]) -> dict[str, torch.Tensor]:
    return {key: torch.cat(values) for key, values in chunks.items()}


def _synthesize(
    payload: dict[str, torch.Tensor], synthesizer: MIMOOFDMSynthesizer
) -> None:
    payload["csi"] = synthesizer(
        payload["path_delays_ns"],
        payload["path_powers_linear"],
        payload["path_phases_rad"],
        payload["aoa_az_deg"],
        payload["aoa_el_deg"],
        payload["aod_az_deg"],
        payload["aod_el_deg"],
        payload["path_mask"],
    )


def _load_dp(
    checkpoint: Mapping[str, Any], device: torch.device
) -> SceneConditionedDelayPowerResidual:
    if checkpoint.get("model_kind") != "scene_delay_power_residual":
        raise ValueError("--dp-checkpoint is not a scene Delay-Power residual")
    model = SceneConditionedDelayPowerResidual(**checkpoint["model_init"]).to(device)
    model.load_state_dict(
        checkpoint.get("ema_state_dict", checkpoint["model_state_dict"])
    )
    return model.requires_grad_(False).eval()


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Build paired No-DP, DP+Copy and DP+AoD-Swap variants from the "
            "same Strongest Anchor raw samples."
        )
    )
    parser.add_argument("--artifact", required=True)
    parser.add_argument("--dp-checkpoint", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--cfg", type=int, choices=(1, 2, 3), default=1)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--device", default="auto")
    args = parser.parse_args()
    if args.batch_size < 1:
        raise ValueError("batch-size must be positive")

    source = torch.load(args.artifact, map_location="cpu", weights_only=False)
    if source.get("condition_type") != "strongest" or source.get("split") != "test":
        raise ValueError("ablation requires a frozen Strongest-AoD Test artifact")
    if not bool(source.get("sampling", {}).get("strongest_anchor_enabled", False)):
        raise ValueError("artifact was not generated by a Strongest Anchor checkpoint")
    raw_label = f"aod_cfg{args.cfg}_raw"
    if raw_label not in source.get("payloads", {}):
        raise ValueError(f"artifact has no {raw_label}")
    target = source.get("target_aod_deg")
    if not isinstance(target, torch.Tensor):
        raise ValueError("artifact has no target_aod_deg")
    raw_source = source["payloads"][raw_label]
    samples = _sample_count(raw_source)
    if target.shape != (samples,):
        raise ValueError("target_aod_deg does not align with the raw samples")

    device = resolve_device(args.device)
    checkpoint = torch.load(
        args.dp_checkpoint, map_location="cpu", weights_only=False
    )
    dp = _load_dp(checkpoint, device)
    system = SystemConfig.from_mapping(source["system"])
    synthesizer = MIMOOFDMSynthesizer(system).to(device).eval()
    chunks: dict[str, dict[str, list[torch.Tensor]]] = {
        name: {} for name in ("no_dp", "dp_pre_rebind", "dp_copy", "dp_swap")
    }

    with torch.inference_mode():
        for start in range(0, samples, args.batch_size):
            stop = min(start + args.batch_size, samples)
            no_dp = _subset(raw_source, start, stop, device)
            current_target = target[start:stop].to(device)
            conditions = no_dp["conditions"].float()
            validity = no_dp["condition_validity"].bool()
            map_ids = no_dp["map_id"].long()
            map_index = dp.map_indices(map_ids)
            output = dp(no_dp, conditions, validity, map_index=map_index)
            pre_rebind = dp.apply_to_payload(no_dp, output)
            copy = enforce_final_strongest_anchor(
                pre_rebind, current_target, strategy="copy"
            )
            swap = enforce_final_strongest_anchor(
                pre_rebind, current_target, strategy="swap"
            )
            for payload in (no_dp, pre_rebind, copy, swap):
                _synthesize(payload, synthesizer)
            for name, payload in (
                ("no_dp", no_dp),
                ("dp_pre_rebind", pre_rebind),
                ("dp_copy", copy),
                ("dp_swap", swap),
            ):
                _append(chunks[name], payload)
            print(
                json.dumps(
                    {
                        "event": "strongest_anchor_rebinding_ablation_progress",
                        "complete": stop,
                        "total": samples,
                    }
                ),
                flush=True,
            )

    payloads = {name: _finish(values) for name, values in chunks.items()}
    changed = payloads["dp_copy"]["strongest_anchor_identity_changed"].bool()
    output = {
        "format_version": 1,
        "model_kind": "strongest_anchor_rebinding_ablation",
        "split": "test",
        "cfg": args.cfg,
        "target_aod_deg": target.cpu(),
        "payloads": {
            "reference": source["payloads"]["reference"],
            "real_query": source["payloads"]["real_query"],
            **payloads,
        },
        "dp_top1_changed": changed,
        "protocol": {
            "paired_raw_samples": True,
            "same_anchor_checkpoint_seed_and_conditions": True,
            "no_dp": "Strongest Anchor B3 output before DP",
            "dp_copy": "DP followed by copying target AoD onto final-power Top1",
            "dp_swap": (
                "DP followed by swapping old Anchor and final-power Top1 AoDs; "
                "the AoD multiset is preserved"
            ),
            "natural_coincident_aods_allowed": True,
        },
        "system": source["system"],
        "sources": {
            "test_artifact": str(Path(args.artifact).resolve()),
            "dp_checkpoint": str(Path(args.dp_checkpoint).resolve()),
            "aod_checkpoint": source.get("sources", {}).get("aod_checkpoint"),
        },
    }
    destination = Path(args.output)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(destination.suffix + ".tmp")
    torch.save(output, temporary)
    temporary.replace(destination)
    print(
        json.dumps(
            {
                "event": "strongest_anchor_rebinding_ablation_complete",
                "output": str(destination.resolve()),
                "samples": samples,
                "dp_top1_changed_samples": int(changed.sum()),
                "dp_top1_changed_rate": float(changed.float().mean()),
            },
            indent=2,
        ),
        flush=True,
    )


if __name__ == "__main__":
    main()
