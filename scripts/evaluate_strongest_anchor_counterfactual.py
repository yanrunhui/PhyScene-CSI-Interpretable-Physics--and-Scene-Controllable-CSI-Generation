#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Mapping

import torch

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from physics_csi.data.delay_power_residual import DelayPowerResidualCacheDataset
from physics_csi.evaluation.aod_support import (
    circular_distance_degrees,
    normalized_condition_features,
    strongest_aod,
)
from physics_csi.evaluation.multipath_recall import (
    FeatureStandardizer,
    manifold_metrics,
    multipath_view_features,
)
from physics_csi.physics.constraints import first_active_path_mask
from physics_csi.utils.io import atomic_json_dump


def _subset(
    payload: Mapping[str, torch.Tensor], mask: torch.Tensor
) -> dict[str, torch.Tensor]:
    samples = int(payload["path_mask"].shape[0])
    return {
        key: value[mask]
        for key, value in payload.items()
        if isinstance(value, torch.Tensor) and value.shape[:1] == (samples,)
    }


def _condition_row(artifact: Mapping[str, Any]) -> tuple[torch.Tensor, torch.Tensor]:
    values = artifact["conditions"]
    row = torch.tensor(
        [[
            float(values["total_power_db"]),
            float(values["delay_spread_ns"]),
            float(values["k_factor_db"]),
            float(values["los_status"]),
        ]]
    )
    validity = torch.ones_like(row, dtype=torch.bool)
    validity[:, 2] = row[:, 3] >= 0.5
    return row, validity


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate a class-B Strongest Anchor artifact against cross-scene "
            "relative multipath statistics without using Map fidelity as a gate."
        )
    )
    parser.add_argument("--artifact", required=True)
    parser.add_argument("--support-cache", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--maximum-condition-distance", type=float, default=1.5)
    parser.add_argument("--maximum-angle-distance-deg", type=float, default=10.0)
    parser.add_argument("--minimum-cross-scene-reference", type=int, default=8)
    parser.add_argument("--minimum-hit-at-10", type=float, default=0.80)
    parser.add_argument("--coverage-k", type=int, default=3)
    args = parser.parse_args()

    artifact = torch.load(args.artifact, map_location="cpu", weights_only=False)
    if artifact.get("model_kind") != "multipath_diffusion_scene_id_strongest_aod_anchor":
        raise ValueError("artifact was not generated by a Strongest Anchor checkpoint")
    support = artifact.get("strongest_anchor_support")
    if not isinstance(support, Mapping) or support.get("class") != "B":
        raise ValueError("counterfactual evaluation requires a class-B artifact")
    generated = artifact.get("generated")
    if not isinstance(generated, Mapping):
        raise ValueError("artifact has no generated multipath payload")
    generated_samples = int(generated["path_mask"].shape[0])
    if generated_samples < 2:
        raise ValueError(
            "counterfactual manifold evaluation requires at least two generated samples"
        )
    cache = torch.load(args.support_cache, map_location="cpu", weights_only=False)
    reference = DelayPowerResidualCacheDataset(cache, "train").reference
    condition_std = torch.as_tensor(cache["b3_statistics"]["condition_std"])
    condition, validity = _condition_row(artifact)
    target = float(artifact["strongest_aod_az_deg"])
    path_count = int(artifact["forced_path_count"])

    reference_features = normalized_condition_features(
        reference["conditions"], reference["condition_validity"], condition_std
    )
    request_features = normalized_condition_features(condition, validity, condition_std)
    measurement = strongest_aod(reference)
    same_discrete = (
        ((reference["conditions"][:, 3] >= 0.5) == (condition[0, 3] >= 0.5))
        & (reference["condition_validity"][:, 2].bool() == validity[0, 2])
        & (reference["path_mask"].bool().sum(-1) == path_count)
        & measurement.valid
        & ~measurement.near_tie
    )
    condition_distance = torch.linalg.vector_norm(
        reference_features - request_features[0], dim=-1
    )
    angle_distance = circular_distance_degrees(
        measurement.angle_deg, torch.tensor(target)
    )
    selected = (
        same_discrete
        & (reference["map_id"].long() != int(artifact["map_id"]))
        & (condition_distance <= args.maximum_condition_distance)
        & (angle_distance <= args.maximum_angle_distance_deg)
    )
    cross_reference = _subset(reference, selected)
    reference_samples = int(selected.sum())
    if reference_samples < args.minimum_cross_scene_reference:
        raise RuntimeError(
            "insufficient cross-scene reference support for a statistical B evaluation: "
            f"{reference_samples} < {args.minimum_cross_scene_reference}"
        )

    generated_measurement = strongest_aod(generated)
    generated_target = torch.full_like(generated_measurement.angle_deg, target)
    error = circular_distance_degrees(
        generated_measurement.angle_deg, generated_target
    )
    generated_features = multipath_view_features(
        generated,
        view="target_centered",
        target_mean_aod_deg=generated_target,
        condition_type="strongest",
    )
    real_features = multipath_view_features(
        cross_reference,
        view="self_centered",
        condition_type="strongest",
    )
    standardizer = FeatureStandardizer.fit(real_features)
    manifold = manifold_metrics(
        standardizer.transform(generated_features),
        standardizer.transform(real_features),
        requested_k=args.coverage_k,
    )

    feasible = generated.get("constraint_feasible")
    physical_feasible_rate = (
        float(feasible.float().mean()) if isinstance(feasible, torch.Tensor) else None
    )
    actual = generated.get("actual_conditions")
    physical_mae = None
    if isinstance(actual, torch.Tensor):
        physical_mae = {
            name: float((actual[:, index] - condition[0, index]).abs().mean())
            for index, name in enumerate(
                ("power_db", "delay_spread_ns", "k_factor_db", "los_status")
            )
            if bool(validity[0, index])
        }
    mask = generated["path_mask"].bool()
    finite_multipath = all(
        bool(torch.isfinite(generated[name]).all())
        for name in (
            "path_delays_ns",
            "path_powers_linear",
            "path_phases_rad",
            "aoa_az_deg",
            "aod_az_deg",
        )
    )
    nonnegative = bool((generated["path_delays_ns"][mask] >= 0.0).all()) and bool(
        (generated["path_powers_linear"][mask] >= 0.0).all()
    )
    los = bool(condition[0, 3] >= 0.5)
    direct_consistent = True
    if los:
        direct_consistent = bool(
            torch.equal(
                generated["direct_path_mask"].bool(), first_active_path_mask(mask)
            )
        )
    basic_physical = finite_multipath and nonnegative and direct_consistent
    hit_at_10 = float((error <= 10.0).float().mean())
    hard_gates = {
        "strongest_hit_at_10": {
            "pass": hit_at_10 >= args.minimum_hit_at_10,
            "observed": hit_at_10,
            "minimum": args.minimum_hit_at_10,
        },
        "physical_constraints": {
            "pass": physical_feasible_rate is not None
            and physical_feasible_rate >= 0.99,
            "feasible_rate": physical_feasible_rate,
            "condition_mae": physical_mae,
        },
        "basic_multipath_physical_reasonableness": {
            "pass": basic_physical,
            "finite": finite_multipath,
            "nonnegative_delay_and_power": nonnegative,
            "los_direct_identity_consistent": direct_consistent,
        },
    }
    report = {
        "format_version": 1,
        "evaluation": "strongest_anchor_class_b_counterfactual",
        "support_class": "B",
        "map_conditioned_fidelity_policy": "diagnostic_only_not_a_hard_gate",
        "samples": generated_samples,
        "cross_scene_reference_samples": reference_samples,
        "strongest_control": {
            "mean_error_deg": float(error.mean()),
            "p95_error_deg": float(torch.quantile(error, 0.95)),
            "hit_at_5_deg": float((error <= 5.0).float().mean()),
            "hit_at_10_deg": hit_at_10,
        },
        "cross_scene_relative_multipath": {
            **manifold.metrics,
            "view": "generated target-centered vs real self-centered",
            "role": "reported as evidence, not converted into Map-fidelity rejection",
        },
        "hard_gates": hard_gates,
        "decision": (
            "physically_reasonable_counterfactual"
            if all(section["pass"] for section in hard_gates.values())
            else "rejected"
        ),
        "sources": {
            "artifact": str(Path(args.artifact).resolve()),
            "support_cache": str(Path(args.support_cache).resolve()),
        },
    }
    atomic_json_dump(report, args.output)
    print(json.dumps(report, ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()
